param(
    [string]$Original = 'D:\casek store copy\OriginalBuild',
    [string]$Ours,
    [string]$Out
)
# MOD-INV (0.4.14): builds ModBaseline.cs = the small data baseline the plugin compares the installed game with (MOD-DATA lines, MODS-HASH).
# Source: the pristine game copy D:\casek store copy\OriginalBuild (Castle Story v1.8.8, Steam build 3418235: every shipped file byte-identical to the installed game,
# checked 2026-11-07) + ModBaseline-ours.csv (our own known variants: seasonal modes, languages, GameLua copies, test map). The scope and exclusion rules are compiled
# from ModInventoryRules.cs itself, so the baseline and the plugin can never disagree about which files count.
# READ-ONLY for the game copy; writes only $Out. Run it by hand when the baseline must change (a game update, a new data file of ours), then rebuild.
# ModBaseline.cs is committed in Source, so compile-only builds (BuildPlugin.ps1) never need OriginalBuild.
$ErrorActionPreference = 'Stop'
$here = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path -Parent $MyInvocation.MyCommand.Path }
if (-not $Ours) { $Ours = Join-Path $here 'ModBaseline-ours.csv' }
if (-not $Out) { $Out = Join-Path $here 'ModBaseline.cs' }
if (-not (Test-Path -LiteralPath $Original)) { throw "pristine game copy not found: $Original" }
$rulesFile = Join-Path $here 'ModInventoryRules.cs'
$wrapper = @'
namespace CastleStorySteam
{
    public static class ModInvGen
    {
        public static bool InScope(string rel) { return ModInventoryRules.InScope(rel); }
        public static string Pack(string text) { return ModInventoryRules.Pack(text); }
        public static string Unpack(string packed) { return ModInventoryRules.Unpack(packed); }
        public static int BaseCount(string text) { return ModInventoryRules.Parse(text).Base.Count; }
        public static string HashFile(string path)
        {
            using (System.Security.Cryptography.MD5 md5 = System.Security.Cryptography.MD5.Create())
            using (System.IO.FileStream fs = new System.IO.FileStream(path, System.IO.FileMode.Open, System.IO.FileAccess.Read, System.IO.FileShare.ReadWrite, 65536))
                return ModInventoryRules.Hex8(md5.ComputeHash(fs));
        }
    }
}
'@
if (-not ('CastleStorySteam.ModInvGen' -as [type])) { Add-Type -TypeDefinition ([IO.File]::ReadAllText($rulesFile) + "`n" + $wrapper) -Language CSharp }

$root = (Resolve-Path -LiteralPath $Original).Path.TrimEnd('\')
$version = ([IO.File]::ReadAllText((Join-Path $root 'version'))).Trim()
$firstpass = [CastleStorySteam.ModInvGen]::HashFile((Join-Path $root 'Castle Story_Data\Managed\Assembly-CSharp-firstpass.dll'))
$base = New-Object System.Collections.Generic.List[string]
foreach ($dir in @('Castle Story_Data\Managed', 'Info')) {
    foreach ($f in [IO.Directory]::GetFiles((Join-Path $root $dir), '*', [IO.SearchOption]::AllDirectories)) {
        $rel = $f.Substring($root.Length + 1).Replace('\', '/')
        if ([CastleStorySteam.ModInvGen]::InScope($rel)) { $base.Add($rel + '|' + [CastleStorySteam.ModInvGen]::HashFile($f)) }
    }
}
$base.Sort([StringComparer]::OrdinalIgnoreCase)
$oursLines = New-Object System.Collections.Generic.List[string]   # not $ours: PowerShell names are case-insensitive and $Ours is the CSV path
foreach ($r in (Import-Csv -LiteralPath $Ours)) { if ($r.rel -and $r.md5_8) { $oursLines.Add('+' + $r.rel.Replace('\', '/') + '|' + $r.md5_8.ToUpperInvariant()) } }
$oursLines.Sort([StringComparer]::OrdinalIgnoreCase)
$text = "#version $version`n#firstpass $firstpass`n" + (($base + $oursLines) -join "`n") + "`n"
$packed = [CastleStorySteam.ModInvGen]::Pack($text)
if ([CastleStorySteam.ModInvGen]::Unpack($packed) -ne $text) { throw 'pack round trip failed' }
if ([CastleStorySteam.ModInvGen]::BaseCount($text) -ne $base.Count) { throw 'parse count mismatch' }
$sb = New-Object System.Text.StringBuilder
[void]$sb.Append("// GENERATED by Make-ModBaseline.ps1 on " + (Get-Date -Format 'yyyy-MM-dd HH:mm') + " from D:\casek store copy\OriginalBuild (" + $version + ", Assembly-CSharp-firstpass " + $firstpass + ") and ModBaseline-ours.csv.`n")
[void]$sb.Append("// Do not edit by hand: run .\Make-ModBaseline.ps1 again. Base entries " + $base.Count + ", our known variants " + $oursLines.Count + ", text " + $text.Length + " chars, packed " + $packed.Length + " chars (deflate + base64).`n")
[void]$sb.Append("// MOD-INV (0.4.14): ModInventory unpacks and parses it with ModInventoryRules (same scope rules as this file was built with).`n")
[void]$sb.Append("namespace CastleStorySteam`n{`n    internal static class ModBaseline`n    {`n")
[void]$sb.Append('        internal const string Version = "' + $version + '";' + "`n")
[void]$sb.Append('        internal const string Firstpass = "' + $firstpass + '";' + "`n")
[void]$sb.Append('        internal const int BaseEntries = ' + $base.Count + ';' + "`n")
[void]$sb.Append('        internal const int OurEntries = ' + $oursLines.Count + ';' + "`n")
[void]$sb.Append("        internal const string Packed =`n")
for ($i = 0; $i -lt $packed.Length; $i += 120) {
    $chunk = $packed.Substring($i, [Math]::Min(120, $packed.Length - $i))
    $end = if ($i + 120 -ge $packed.Length) { ';' } else { ' +' }
    [void]$sb.Append('            "' + $chunk + '"' + $end + "`n")
}
[void]$sb.Append("    }`n}`n")
[IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Output ("ModBaseline.cs written: " + $version + ", firstpass " + $firstpass + ", base " + $base.Count + ", ours " + $oursLines.Count + ", text " + $text.Length + " chars, packed " + $packed.Length + " chars, file " + (Get-Item -LiteralPath $Out).Length + " bytes")
