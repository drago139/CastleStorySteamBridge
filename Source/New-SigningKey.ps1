# One-time: creates the RSA key that signs Steam Bridge updates.
#   private key -> C:\Users\<you>\.castlestory-signing\private-key.xml  (NEVER share or put it in a project/archive; back it up)
#   public key  -> Source\UpdateKey.cs (compiled into the plugin and the installer)
# If the private key is lost, a new key means every player must install the bridge manually once.
param([switch]$Force)
$ErrorActionPreference = 'Stop'
$dir = Join-Path $env:USERPROFILE '.castlestory-signing'
$private = Join-Path $dir 'private-key.xml'
if ((Test-Path $private) -and -not $Force) { throw "Key already exists: $private (use -Force to replace it; old updates will stop being accepted)" }
New-Item -ItemType Directory -Force $dir | Out-Null
$rsa = New-Object System.Security.Cryptography.RSACryptoServiceProvider(2048)
[System.IO.File]::WriteAllText($private, $rsa.ToXmlString($true), (New-Object System.Text.UTF8Encoding($false)))
$public = $rsa.ToXmlString($false).Replace('"', '\"')
$code = "namespace CastleStorySteam`r`n{`r`n    // Public half of the update-signing key (generated by New-SigningKey.ps1).`r`n    internal static class UpdateKey { internal const string PublicXml = `"$public`"; }`r`n}`r`n"
[System.IO.File]::WriteAllText((Join-Path $PSScriptRoot 'UpdateKey.cs'), $code, (New-Object System.Text.UTF8Encoding($true)))
"private key: $private"
"public key written to Source\UpdateKey.cs"
